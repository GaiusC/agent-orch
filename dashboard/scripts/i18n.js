let language='zh-CN';
try { if(localStorage.getItem('agentOrchWorkspaceLanguage')==='en') language='en'; } catch {}
export function getLanguage(){return language;}
export function locale(){return language==='en'?'en-GB':'zh-CN';}
export function setLanguage(value){language=value==='en'?'en':'zh-CN';try{localStorage.setItem('agentOrchWorkspaceLanguage',language);}catch{}}
export function t(key,values={}){
  if(key===undefined||key===null)return key;
  const source=language==='en'?(english[key]??key):key;
  return String(source).replace(/\{(p\d+)\}/g,(token,name)=>Object.hasOwn(values,name)?String(values[name]):token);
}
export function translateStatic(root=document){
  document.documentElement.lang=language;
  root.querySelectorAll('[data-i18n]').forEach(node=>{node.textContent=t(node.dataset.i18n);});
  for(const attr of ['title','aria-label'])root.querySelectorAll(`[data-i18n-${attr}]`).forEach(node=>node.setAttribute(attr,t(node.getAttribute(`data-i18n-${attr}`))));
  document.querySelectorAll('[data-language-toggle]').forEach(toggle=>{
    toggle.textContent=language==='en'?'中文':'EN';toggle.setAttribute('aria-label',language==='en'?'切换到中文':'Switch to English');toggle.title=toggle.getAttribute('aria-label');
  });
}
